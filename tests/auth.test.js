import test from "node:test";
import assert from "node:assert/strict";
import http from "node:http";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { sessionClient } from "./support/client.js";

test("邮箱注册登录、固定身份、跨账号隔离、跨浏览器草稿附件和访客恢复", async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "report-auth-"));
  const legacy = { reports: [{ id: "old-report", status: "待受理", receivedAt: "2026-01-01" }], logs: [], sessions: [{ id: "old-chat", learnerId: "public", userId: null, messages: [], updatedAt: "2026-01-01" }], memories: { "public:legacy": { longTerm: "旧测试数据", shortTerm: [] } }, learning: [{ id: "old-lesson", learnerId: "teacher-1", materialId: "report-duty" }] };
  fs.writeFileSync(path.join(dir, "database.json"), JSON.stringify(legacy));
  const received = [];
  const upstream = http.createServer(async (req, res) => {
    const chunks = []; for await (const chunk of req) chunks.push(chunk);
    const b = JSON.parse(Buffer.concat(chunks)); received.push(b); res.setHeader("Content-Type", "application/json");
    const tool = b.tools && !b.messages.some(m => m.role === "tool");
    const message = tool ? { tool_calls: [{ id: "prepare", type: "function", function: { name: "prepare_report_draft", arguments: JSON.stringify({ identity: "医护人员", description: "虚构事件", types: ["身体虐待"] }) } }] } : { content: b.tools ? "已准备草稿。" : JSON.stringify({ identity: "医护人员", description: "虚构事件", types: ["身体虐待"] }) };
    res.end(JSON.stringify({ choices: [{ message }] }));
  });
  await new Promise(resolve => upstream.listen(0, "127.0.0.1", resolve));
  process.env.DATA_DIR = dir; process.env.AI_CATALOG_ENABLED = "0"; process.env.FREE_API_KEY = "local-test-placeholder";
  process.env.AI_BASE_URL = "http://127.0.0.1:" + upstream.address().port + "/v1";
  const { server } = await import("../server.js"); await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const base = "http://127.0.0.1:" + server.address().port;
  const a = sessionClient(base), b = sessionClient(base), secondBrowser = sessionClient(base), model = "[故人情]gemini-3.8-flash";
  const call = async (client, url, body, method = body ? "POST" : "GET", headers = {}) => { const r = await client(url, { method, headers: { "Content-Type": "application/json", ...headers }, ...(body ? { body: JSON.stringify(body) } : {}) }); return { status: r.status, data: await r.json(), headers: r.headers }; };
  try {
    const guest = (await call(a, "/api/auth/me")).data;
    assert.equal(guest.authenticated, false);
    assert.equal((await call(a, "/api/sessions")).data.length, 0, "旧未绑定会话不能公开给访客");
    assert.equal((await call(a, "/api/memory")).data.longTerm, "");
    assert.equal((await call(a, "/api/learning")).data.length, 0);
    assert.equal((await call(a, "/api/my-reports")).data.length, 0);
    const guestChat = (await call(a, "/api/sessions", { kind: "qa", model })).data;
    const guestTraining = await call(a, "/api/sessions", { kind: "training", model, caseId: "school-injury" }); assert.equal(guestTraining.status, 201);
    assert.equal((await call(a, "/api/auth/register", { email: "not-an-email", identity: "教师/教育工作者" })).status, 400);
    const registration = await call(a, "/api/auth/register", { email: " Teacher@Example.TEST ", name: "林老师", identity: "教师/教育工作者", password: "ignored-password" });
    assert.equal(registration.status, 201); assert.equal(registration.data.user.email, "teacher@example.test");
    assert.equal(registration.data.user.identity, "教师/教育工作者");
    assert.match(registration.headers.get("set-cookie"), /HttpOnly/); assert.match(registration.headers.get("set-cookie"), /SameSite=Lax/);
    assert.doesNotMatch(JSON.stringify(registration.data), /passwordHash|salt|123456/);
    assert.equal((await call(a, "/api/sessions")).data.length, 0, "注册不自动认领访客或旧记录");
    assert.equal((await call(b, "/api/auth/register", { email: "teacher@example.test", identity: "教师/教育工作者" })).status, 409);
    assert.equal((await call(b, "/api/auth/login", { email: "teacher@example.test", password: "wrong" })).status, 401);
    assert.equal((await call(b, "/api/auth/register", { email: "doctor@example.test", identity: "医护人员" })).status, 201);
    const chat = (await call(a, "/api/sessions", { kind: "qa", model, learnerId: b.cookie() })).data;
    const reply = await call(a, "/api/sessions/" + chat.id + "/messages", { model, content: "我在描述医护案例，请整理报告" });
    assert.equal(reply.status, 200); assert.equal(reply.data.reportDraft.fields.identity, "教师/教育工作者");
    assert.ok(received[0].messages[0].content.includes("当前登录用户的报告身份是教师/教育工作者"));
    const toolValue = JSON.parse(received.at(-1).messages.find(m => m.role === "tool").content); assert.equal(toolValue.fields.identity, "教师/教育工作者");
    const manual = await call(a, "/api/sessions/" + chat.id + "/report-draft", { model }); assert.equal(manual.data.fields.identity, "教师/教育工作者");
    assert.equal((await call(b, "/api/sessions/" + chat.id, undefined, "GET", { "X-Chat-User": registration.data.user.id })).status, 404);
    assert.equal((await call(b, "/api/sessions/" + chat.id, undefined, "DELETE")).status, 404);
    await call(a, "/api/memory", { longTerm: "回答先给步骤" }); assert.equal((await call(b, "/api/memory")).data.longTerm, "");
    await call(a, "/api/learning", { materialId: "teacher-duty" }); assert.equal((await call(b, "/api/learning")).data.length, 0);
    assert.equal((await call(b, "/api/units/" + encodeURIComponent(registration.data.profile.unitId))).status, 404);
    const draftId = crypto.randomUUID(), fields = { identity: "医护人员", types: ["身体虐待"], description: "账号草稿", reporter: {} };
    const saved = await call(a, "/api/drafts/" + draftId, { fields, scrollY: 760 }, "PUT"); assert.equal(saved.data.fields.identity, "教师/教育工作者");
    const attached = await call(a, "/api/drafts/" + draftId + "/attachment", { revision: saved.data.revision, attachment: { name: "evidence.txt", mime: "text/plain", data: Buffer.from("fictional evidence").toString("base64") } }, "PUT");
    assert.equal(attached.status, 200);
    assert.equal((await call(a, "/api/drafts/" + draftId, { fields, revision: saved.data.revision, scrollY: 0 }, "PUT")).status, 409, "旧页面不能覆盖较新草稿");
    assert.equal((await call(b, "/api/drafts")).data.length, 0); assert.equal((await call(b, "/api/drafts/" + draftId + "/attachment")).status, 404);
    assert.equal((await call(b, "/api/drafts/" + draftId, undefined, "DELETE")).status, 404);
    await call(secondBrowser, "/api/auth/login", { email: "teacher@example.test", password: "123456" });
    assert.equal((await call(secondBrowser, "/api/sessions")).data[0].id, chat.id);
    assert.equal((await call(secondBrowser, "/api/memory")).data.longTerm, "回答先给步骤");
    assert.equal((await call(secondBrowser, "/api/drafts")).data[0].scrollY, 760);
    assert.equal(Buffer.from((await call(secondBrowser, "/api/drafts/" + draftId + "/attachment")).data.data, "base64").toString(), "fictional evidence");
    assert.equal((await call(a, "/api/drafts/" + draftId, { revision: saved.data.revision }, "DELETE")).status, 409, "旧页面不能删除较新版本");
    assert.equal((await call(a, "/api/drafts/" + draftId, { revision: attached.data.revision }, "DELETE")).status, 200);
    assert.equal((await call(secondBrowser, "/api/drafts/" + draftId, { fields, revision: attached.data.revision }, "PUT")).status, 410, "延迟保存不能重新创建已删除草稿");
    const report = await call(a, "/api/reports", { ...fields, region: "虚构地区", address: "虚构学校", occurredAt: "2026-10-12T09:00", age: "7-13岁", consent: true }); assert.equal(report.status, 201);
    assert.equal((await call(secondBrowser, "/api/my-reports")).data[0].id, report.data.id); assert.equal((await call(b, "/api/my-reports")).data.length, 0);
    assert.equal((await call(a, "/api/memory", { longTerm: "should not save" }, "POST", { Origin: "https://wrong-origin.example" })).status, 403);
    const oldCookie = a.cookie();
    const logout = (await call(a, "/api/auth/logout", {})).data;
    assert.equal(logout.authenticated, false); assert.equal(logout.ownerId, guest.ownerId);
    assert.ok((await call(a, "/api/sessions")).data.some(s => s.id === guestChat.id));
    assert.equal((await call(a, "/api/sessions")).data.some(s => s.id === chat.id), false);
    const revoked = await (await fetch(base + "/api/auth/me", { headers: { Cookie: oldCookie } })).json(); assert.equal(revoked.authenticated, false);
    assert.equal((await call(a, "/api/drafts")).status, 401);
    assert.equal((await call(a, "/api/memory", { longTerm: "stale account" }, "POST", { "X-Record-Owner": registration.data.ownerId })).status, 409);
    const stored = JSON.parse(fs.readFileSync(path.join(dir, "database.json"), "utf8"));
    assert.ok(stored.sessions.some(s => s.id === "old-chat")); assert.ok(stored.reports.some(r => r.id === "old-report"));
    assert.equal(stored.reports.find(r => r.id === report.data.id).identity, "教师/教育工作者");
    assert.ok(stored.accounts.every(u => /^[a-f0-9]{128}$/.test(u.passwordHash) && !u.password));
    assert.equal(fs.readdirSync(path.join(dir, "backups")).length, 1);
  } finally {
    server.closeAllConnections(); upstream.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await new Promise(resolve => upstream.close(resolve));
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
